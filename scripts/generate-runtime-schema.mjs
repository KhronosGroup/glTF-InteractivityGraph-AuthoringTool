import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";

const root = path.resolve(new URL("..", import.meta.url).pathname);
const specRoot = process.env.KHR_INTERACTIVITY_GLTF_REPO;
if (!specRoot)
    throw new Error(
        "Set KHR_INTERACTIVITY_GLTF_REPO to the current Khronos glTF checkout.",
    );
const require = createRequire(
    path.join(root, "src/BasicBehaveEngine/package.json"),
);
const { rollup } = await import(require.resolve("rollup"));
const { babel } = await import(require.resolve("@rollup/plugin-babel"));
const { nodeResolve } = await import(
    require.resolve("@rollup/plugin-node-resolve")
);
const preset = require.resolve("@babel/preset-typescript");
const bundle = await rollup({
    input: path.join(root, "src/authoring/spec/nodes.ts"),
    plugins: [
        nodeResolve({ extensions: [".ts", ".js"] }),
        babel({
            babelHelpers: "bundled",
            extensions: [".ts"],
            presets: [[preset, { allowDeclareFields: true }]],
        }),
    ],
});
const { output } = await bundle.generate({ format: "es" });
const { interactivityNodeSpecs, standardTypes } = await import(
    "data:text/javascript;base64," +
        Buffer.from(output[0].code).toString("base64")
);
await bundle.close();
const operations = Object.fromEntries(
    interactivityNodeSpecs.map((spec) => [
        spec.op,
        {
            extension: spec.extension,
            inputs: Object.fromEntries(
                Object.entries(spec.values?.input ?? {}).map(([id, socket]) => [
                    id,
                    {
                        types: (socket.typeOptions ?? [socket.type])
                            .map((index) => standardTypes[index]?.signature)
                            .filter(Boolean),
                        group: socket.typeGroup,
                    },
                ]),
            ),
            outputs: Object.fromEntries(
                Object.entries(spec.values?.output ?? {}).map(
                    ([id, socket]) => [
                        id,
                        {
                            types: (socket.typeOptions ?? [socket.type])
                                .map((index) => standardTypes[index]?.signature)
                                .filter(Boolean),
                            group: socket.typeGroup,
                        },
                    ],
                ),
            ),
        },
    ]),
);
const schemaDir = path.join(
    specRoot,
    "extensions/2.0/Khronos/KHR_interactivity/schema",
);
const schemas = {};
// Documentation annotations do not participate in runtime validation. Visit only
// schema objects, so identically named properties and literal values stay intact.
function runtimeSchema(schema) {
    if (typeof schema !== "object" || schema === null) return schema;
    const result = { ...schema };
    for (const key of [
        "title", "description", "default", "examples",
        "gltf_detailedDescription", "gltf_sectionDescription",
    ]) delete result[key];
    for (const key of ["properties", "$defs", "patternProperties", "dependentSchemas"])
        if (result[key]) result[key] = Object.fromEntries(
            Object.entries(result[key]).map(([name, child]) => [name, runtimeSchema(child)]),
        );
    for (const key of ["allOf", "anyOf", "oneOf", "prefixItems"])
        if (result[key]) result[key] = result[key].map(runtimeSchema);
    for (const key of ["items", "additionalProperties", "not", "if", "then", "else"])
        if (result[key] !== undefined) result[key] = runtimeSchema(result[key]);
    return result;
}
for (const file of await fs.readdir(schemaDir)) {
    if (file.endsWith(".schema.json"))
        schemas[file] = JSON.parse(
            await fs.readFile(path.join(schemaDir, file), "utf8"),
        );
}
for (const file of [
    "glTFProperty.schema.json",
    "glTFChildOfRootProperty.schema.json",
    "glTFid.schema.json",
    "extensions.schema.json",
    "extras.schema.json",
]) {
    schemas[file] = JSON.parse(
        await fs.readFile(
            path.join(specRoot, "specification/2.0/schema", file),
            "utf8",
        ),
    );
}
const target = path.join(
    root,
    "src/BasicBehaveEngine/generated/interactivitySchemas.ts",
);
await fs.mkdir(path.dirname(target), { recursive: true });
// One operation per line keeps the generated catalogue reviewable without
// expanding every small socket descriptor across many lines.
const operationData = "{\n" + Object.entries(operations)
    .map(([op, schema]) => `  ${JSON.stringify(op)}: ${JSON.stringify(schema)}`)
    .join(",\n") + "\n}";
const runtimeSchemas = Object.fromEntries(
    Object.entries(schemas).map(([file, schema]) => [file, runtimeSchema(schema)]),
);
await fs.writeFile(
    target,
    `// Generated by scripts/generate-runtime-schema.mjs from Khronos schemas and the operation catalogue.\n// Runtime validation rules only; documentation annotations are omitted.\nexport const INTERACTIVITY_SCHEMAS: Record<string, any> = ${JSON.stringify(runtimeSchemas, null, 2)};\nexport const OPERATION_SCHEMAS: Record<string, { extension?: string; inputs: Record<string, { types: string[]; group?: string }>; outputs: Record<string, { types: string[]; group?: string }> }> = ${operationData};\n`,
);
console.log(
    `Generated runtime validation for ${Object.keys(operations).length} operations.`,
);
